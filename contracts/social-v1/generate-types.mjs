// Deliberately small compiler for this schema's structural subset. JSON Schema
// remains authoritative for numeric, conditional and collection constraints.
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

const schemaUrl = new URL('./shared.schema.json', import.meta.url);
const target = new URL('../../functions/src/domain/socialV1.ts', import.meta.url);
const raw = readFileSync(schemaUrl, 'utf8');
const schema = JSON.parse(raw);
const marker = '// END GENERATED DECLARATIONS\n';
function type(s) {
  if (s.$ref) return s.$ref.split('/').at(-1);
  if ('const' in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map(v => JSON.stringify(v)).join(' | ');
  if (s.oneOf || s.anyOf) return (s.oneOf ?? s.anyOf).map(v => `(${type(v)})`).join(' | ');
  if (Array.isArray(s.type)) return s.type.map(t => type({type:t})).join(' | ');
  if (s.type === 'array') return `Array<${type(s.items)}>`;
  if (s.type === 'object') return '{\n' + Object.entries(s.properties).map(([k,v]) =>
    `  ${k}${s.required.includes(k) ? '' : '?'}: ${type(v)};`).join('\n') + '\n}';
  if (s.type === 'string' || s.type === 'number' || s.type === 'boolean' || s.type === 'null') return s.type;
  if (s.type === 'integer') return 'number';
  if (s.allOf?.[0]?.$ref && s.allOf[1]?.properties?.kind)
    return `(${type(s.allOf[0])} & {kind: ${type(s.allOf[1].properties.kind)}})`;
  throw new Error(`Unsupported structural schema: ${JSON.stringify(s)}`);
}
const generated = '// Generated by contracts/social-v1/generate-types.mjs. Do not edit this section.\n' +
  `export const SOCIAL_V1_CONTRACT = ${JSON.stringify(schema.title)} as const;\n` +
  `export const SOCIAL_V1_SCHEMA_SHA256 = '${createHash('sha256').update(raw).digest('hex')}';\n\n` +
  Object.entries(schema.$defs).map(([name, s]) => `export type ${name} = ${type(s)};\n`).join('\n') +
  '\nexport type SocialV1Records = {\n' + schema.$defs.RecordType.enum.map(n => `  ${n}: ${n};`).join('\n') + '\n};\n' +
  'export type SocialV1Envelope = {[K in RecordType]: {contract: typeof SOCIAL_V1_CONTRACT; recordType: K; value: SocialV1Records[K]}}[RecordType];\n' + marker;
const current = readFileSync(target, 'utf8');
if (!current.includes(marker)) throw new Error('Missing generated declaration marker');
const expected = generated + current.split(marker)[1];
if (process.argv.includes('--check')) {
  if (current !== expected) throw new Error('Stale socialV1.ts: run node contracts/social-v1/generate-types.mjs');
} else writeFileSync(target, expected);
